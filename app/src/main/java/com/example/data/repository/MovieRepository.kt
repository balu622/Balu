    val watchlistMovies: Flow<List<Movie>> = movieDao.getAllWatchlist().map { entities ->
        entities.map { it.toMovie() }
    }

    fun isBookmarked(movieId: String): Flow<Boolean> = movieDao.isMovieBookmarked(movieId)

    suspend fun toggleBookmark(movie: Movie) {
        if (movie.isBookmarked) {
            movieDao.deleteMovieById(movie.id)
        } else {
            movieDao.insertMovie(MovieEntity.fromMovie(movie.copy(isBookmarked = true)))
        }
    }

    suspend fun removeBookmark(movieId: String) {
        movieDao.deleteMovieById(movieId)
